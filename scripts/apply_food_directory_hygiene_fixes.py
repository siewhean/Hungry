#!/usr/bin/env python3
"""
scripts/apply_food_directory_hygiene_fixes.py

Applies the 1,859 Food Directory hygiene and anti-contamination remediations
generated by the Directory Stall Hygiene Auditor (Pass 16 / hungry-fnb-enrichment-audit):
1. Clears 1,105 contaminated Website cells (food court operator corporate domains, food blogs, etc.)
2. Harmonizes 735 Menu / Price labels to match actual Menu URL platforms
3. Remediates 17 entity identity descriptors in F&B Name and Registered Business Name
4. Synchronizes 2 Google Maps URLs with Place ID bitwise parity

Saves atomically with ZipFile verification.
"""

import os
import sys
import json
import zipfile
import openpyxl

MASTER_PATH = "outputs/01a17680-a363-77e1-bf29-8b3dd917e8b8/Hungry_Menu_and_Food_Directory_0A_filled_checked_plus_new_stalls_2026-11-04.xlsx"
MANIFEST_PATH = "data/review_runs/food_directory_audit_report_2026-11-14.json"

def main():
    print(f"Loading remediation manifest from: {MANIFEST_PATH} ...")
    with open(MANIFEST_PATH, "r", encoding="utf-8") as f:
        data = json.load(f)
        
    manifest = data["remediation_action_manifest"]
    clean_web = manifest.get("clear_website_contamination", [])
    harm_labels = manifest.get("harmonize_menu_price_labels", [])
    rem_ident = manifest.get("remediate_identity_descriptors", [])
    regen_maps = manifest.get("regenerate_google_maps_urls", [])
    
    total_actions = len(clean_web) + len(harm_labels) + len(rem_ident) + len(regen_maps)
    print(f"Total remediation actions to apply: {total_actions}")
    print(f"  Website contamination cleans: {len(clean_web)}")
    print(f"  Menu / Price label harmonizations: {len(harm_labels)}")
    print(f"  Identity descriptor remediations: {len(rem_ident)}")
    print(f"  Google Maps URL synchronizations: {len(regen_maps)}")
    
    print(f"Loading master workbook from: {MASTER_PATH} ...")
    wb = openpyxl.load_workbook(MASTER_PATH)
    ws_fd = wb["Food Directory"]
    
    fd_header = [str(c.value or "").strip() for c in ws_fd[1]]
    fd_h = {k: i + 1 for i, k in enumerate(fd_header)}  # 1-based column indices
    
    # 1. Clear website contamination
    web_cleared = 0
    web_col = fd_h["Website"]
    for item in clean_web:
        r = item["row"]
        cell = ws_fd.cell(row=r, column=web_col)
        cell.value = None
        web_cleared += 1
    print(f"Applied {web_cleared} Website cleans.")
    
    # 2. Harmonize Menu / Price labels
    labels_fixed = 0
    mp_col = fd_h["Menu / Price"]
    for item in harm_labels:
        r = item["row"]
        cell = ws_fd.cell(row=r, column=mp_col)
        cell.value = item["new_value"]
        labels_fixed += 1
    print(f"Applied {labels_fixed} Menu / Price label harmonizations.")
    
    # 3. Remediate identity descriptors
    ident_fixed = 0
    fnb_col = fd_h["F&B Name"]
    rbn_col = fd_h["Registered Business Name"]
    for item in rem_ident:
        r = item["row"]
        if "proposed_fnb_name" in item:
            ws_fd.cell(row=r, column=fnb_col).value = item["proposed_fnb_name"]
        if "proposed_registered_business_name" in item:
            new_rbn = item["proposed_registered_business_name"]
            ws_fd.cell(row=r, column=rbn_col).value = new_rbn if new_rbn else None
        ident_fixed += 1
    print(f"Applied {ident_fixed} identity descriptor fixes.")
    
    # 4. Synchronize Google Maps URLs
    maps_fixed = 0
    maps_col = fd_h["Google Maps URL"]
    for item in regen_maps:
        r = item["row"]
        ws_fd.cell(row=r, column=maps_col).value = item["new_value"]
        maps_fixed += 1
    print(f"Applied {maps_fixed} Google Maps URL synchronizations.")
    
    # Save atomically
    tmp_path = MASTER_PATH + ".tmp_dir_hygiene"
    print(f"Saving workbook to temporary path: {tmp_path} ...")
    wb.save(tmp_path)
    
    with zipfile.ZipFile(tmp_path, "r") as z:
        assert z.testzip() is None, "ZIP integrity test failed on temporary save"
        
    os.replace(tmp_path, MASTER_PATH)
    print(f"Successfully committed all {total_actions} Food Directory hygiene fixes to {MASTER_PATH}")

if __name__ == "__main__":
    main()
