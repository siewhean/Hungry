#!/usr/bin/env node
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const TEXT_EXTENSIONS = new Set([".cjs", ".js", ".jsx", ".json", ".md", ".mjs", ".ts", ".tsx"]);
const ASSET_EXTENSIONS = new Set([".jpg", ".jpeg", ".png", ".webp"]);
const IGNORED_DIRS = new Set([".git", ".next", "build", "dist", "node_modules"]);

const groups = [
  {
    key: "mobileDiscover",
    label: "Mobile discover assets",
    assetDir: "src/assets/discover",
    scanDirs: ["src", "tasks"],
    maxTotalMiB: 6,
    maxLargestFileMiB: 1,
    source:
      "Generated bitmap food art and app-card artwork; provenance is recorded in tasks/release-evidence/asset-provenance.md.",
  },
  {
    key: "passport",
    label: "Passport/gamification assets",
    assetDir: "src/assets/gamification/passport",
    scanDirs: ["src", "scripts", "tasks"],
    maxTotalMiB: 1,
    maxLargestFileMiB: 0.1,
    source:
      "Generated by scripts/generate-passport-assets.mjs; no external stock art dependency is required.",
  },
  {
    key: "onboardingFood",
    label: "Onboarding food images",
    assetDir: "src/assets/onboarding/food",
    scanDirs: ["src", "tasks"],
    maxTotalMiB: 15,
    maxLargestFileMiB: 0.8,
    provenancePath: "tasks/release-evidence/asset-provenance.md",
    requiredProvenancePatterns: [
      /Generated with the built-in image generation workflow as professional restaurant-style generated food photography/,
      /No homemade photos, casual phone shots, stock providers, or scraped food photos are allowed/,
      /generated restaurant\/menu photography with controlled lighting, polished plating, clean tableware/,
      /no casual home-kitchen counters, phone flash, cluttered homemade staging, watermark text, stock-photo providers, or scraped food photos/,
    ],
    source:
      "Generated professional restaurant-style food photography for onboarding; no homemade photos, stock providers, or scraped food photos are referenced.",
  },
  {
    key: "marketingFood",
    label: "Marketing food images",
    assetDir: "marketing/website/web-v2/public/images/food",
    scanDirs: ["marketing/website/web-v2/src", "marketing/website/web-v2/public"],
    maxTotalMiB: 45,
    maxLargestFileMiB: 1.5,
    source:
      "Web-only marketing food imagery; keep out of mobile bundle unless an app reference is added intentionally.",
  },
];

function walkFiles(relativeDir, predicate = () => true) {
  const absoluteDir = path.join(root, relativeDir);
  if (!existsSync(absoluteDir)) return [];
  const files = [];

  function visit(currentDir) {
    for (const entry of readdirSync(currentDir, { withFileTypes: true })) {
      if (entry.isDirectory()) {
        if (IGNORED_DIRS.has(entry.name)) continue;
        visit(path.join(currentDir, entry.name));
        continue;
      }
      if (!entry.isFile()) continue;
      const absolutePath = path.join(currentDir, entry.name);
      const relativePath = path.relative(root, absolutePath);
      if (predicate(relativePath)) files.push(relativePath);
    }
  }

  visit(absoluteDir);
  return files.sort();
}

function bytesToMiB(bytes) {
  return Number((bytes / 1024 / 1024).toFixed(2));
}

function collectTextCorpus(scanDirs) {
  return scanDirs
    .flatMap((dir) =>
      walkFiles(dir, (file) => TEXT_EXTENSIONS.has(path.extname(file).toLowerCase())),
    )
    .map((file) => readFileSync(path.join(root, file), "utf8"))
    .join("\n");
}

function auditGroup(group) {
  const assets = walkFiles(group.assetDir, (file) =>
    ASSET_EXTENSIONS.has(path.extname(file).toLowerCase()),
  );
  const corpus = collectTextCorpus(group.scanDirs);
  const entries = assets.map((file) => {
    const { size } = statSync(path.join(root, file));
    const basename = path.basename(file);
    return {
      file,
      sizeBytes: size,
      sizeMiB: bytesToMiB(size),
      referenced: corpus.includes(basename) || corpus.includes(file),
    };
  });

  const totalBytes = entries.reduce((sum, entry) => sum + entry.sizeBytes, 0);
  const referencedBytes = entries
    .filter((entry) => entry.referenced)
    .reduce((sum, entry) => sum + entry.sizeBytes, 0);
  const largest = [...entries].sort((a, b) => b.sizeBytes - a.sizeBytes).slice(0, 8);

  return {
    key: group.key,
    label: group.label,
    assetDir: group.assetDir,
    source: group.source,
    budget: {
      maxTotalMiB: group.maxTotalMiB,
      maxLargestFileMiB: group.maxLargestFileMiB,
    },
    fileCount: entries.length,
    referencedCount: entries.filter((entry) => entry.referenced).length,
    totalMiB: bytesToMiB(totalBytes),
    referencedMiB: bytesToMiB(referencedBytes),
    unreferencedMiB: bytesToMiB(totalBytes - referencedBytes),
    largest,
    unreferenced: entries.filter((entry) => !entry.referenced).map((entry) => entry.file),
  };
}

const report = {
  generatedAt: new Date().toISOString(),
  groups: groups.map(auditGroup),
};

const failures = [];

for (const group of report.groups) {
  console.log(`\n${group.label}`);
  console.log(`- path: ${group.assetDir}`);
  console.log(
    `- files: ${group.fileCount} total, ${group.referencedCount} referenced by scanned source`,
  );
  console.log(
    `- size: ${group.totalMiB} MiB total, ${group.referencedMiB} MiB referenced, ${group.unreferencedMiB} MiB unreferenced`,
  );
  console.log(
    `- budget: ${group.budget.maxTotalMiB} MiB total, ${group.budget.maxLargestFileMiB} MiB max file`,
  );
  console.log(`- source/licensing: ${group.source}`);
  if (group.totalMiB > group.budget.maxTotalMiB) {
    failures.push(
      `${group.label} total size ${group.totalMiB} MiB exceeds ${group.budget.maxTotalMiB} MiB`,
    );
  }
  const oversizedFiles = group.largest.filter(
    (entry) => entry.sizeMiB > group.budget.maxLargestFileMiB,
  );
  for (const entry of oversizedFiles) {
    failures.push(
      `${group.label} file ${entry.file} is ${entry.sizeMiB} MiB and exceeds ${group.budget.maxLargestFileMiB} MiB`,
    );
  }
  if (group.unreferenced.length > 0) {
    failures.push(`${group.label} has ${group.unreferenced.length} unreferenced asset(s)`);
  }
  if (group.provenancePath) {
    const provenanceAbsolutePath = path.join(root, group.provenancePath);
    if (!existsSync(provenanceAbsolutePath)) {
      failures.push(`${group.label} is missing provenance file ${group.provenancePath}`);
    } else {
      const provenance = readFileSync(provenanceAbsolutePath, "utf8");
      for (const pattern of group.requiredProvenancePatterns ?? []) {
        if (!pattern.test(provenance)) {
          failures.push(`${group.label} provenance does not satisfy ${pattern}`);
        }
      }
    }
  }
  if (group.largest.length > 0) {
    console.log("- largest:");
    for (const entry of group.largest) {
      console.log(
        `  - ${entry.sizeMiB} MiB ${entry.referenced ? "referenced" : "unreferenced"} ${entry.file}`,
      );
    }
  }
  if (group.unreferenced.length > 0) {
    console.log("- unreferenced files:");
    for (const file of group.unreferenced) console.log(`  - ${file}`);
  }
}

console.log("\nJSON");
console.log(JSON.stringify(report, null, 2));

if (failures.length > 0) {
  console.error("\nAsset audit failed:");
  for (const failure of failures) {
    console.error(`- ${failure}`);
  }
  process.exit(1);
}
