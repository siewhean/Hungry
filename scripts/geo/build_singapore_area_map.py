"""Builds src/features/location/singaporeAreaMap.generated.ts from the URA Master Plan 2014
planning-area boundaries (data.gov.sg, Singapore Open Data Licence), via
https://raw.githubusercontent.com/yinshanyang/singapore/master/maps/2-planning-area.geojson

Usage: python3 scripts/geo/build_singapore_area_map.py <planning-area.geojson>
Rings are simplified (Douglas-Peucker) and projected to a 1000-wide viewBox so the app can
draw the map offline with react-native-svg.
"""

import json
import math
import sys

WIDTH = 1000
TOLERANCE = 1.6  # viewBox units
MIN_RING_AREA = 6.0  # drop specks (tiny islands)
OUT = "src/features/location/singaporeAreaMap.generated.ts"


def rings_of(geometry):
    if geometry["type"] == "Polygon":
        return [geometry["coordinates"][0]]
    return [polygon[0] for polygon in geometry["coordinates"]]


def perpendicular(p, a, b):
    if a == b:
        return math.dist(p, a)
    (x, y), (x1, y1), (x2, y2) = p, a, b
    return abs((y2 - y1) * x - (x2 - x1) * y + x2 * y1 - y2 * x1) / math.dist(a, b)


def simplify(points, tolerance):
    if len(points) < 3:
        return points
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        start, end = stack.pop()
        best, index = 0.0, -1
        for i in range(start + 1, end):
            d = perpendicular(points[i], points[start], points[end])
            if d > best:
                best, index = d, i
        if best > tolerance and index > 0:
            keep[index] = True
            stack.append((start, index))
            stack.append((index, end))
    return [p for p, k in zip(points, keep) if k]


def ring_area(points):
    return abs(
        sum(
            points[i][0] * points[i + 1][1] - points[i + 1][0] * points[i][1]
            for i in range(len(points) - 1)
        )
    ) / 2


def main(path):
    features = json.load(open(path))["features"]
    lons = [c[0] for f in features for r in rings_of(f["geometry"]) for c in r]
    lats = [c[1] for f in features for r in rings_of(f["geometry"]) for c in r]
    min_lon, max_lon, min_lat, max_lat = min(lons), max(lons), min(lats), max(lats)
    kx = math.cos(math.radians((min_lat + max_lat) / 2))
    scale = WIDTH / ((max_lon - min_lon) * kx)
    height = round((max_lat - min_lat) * scale)

    areas = []
    for feature in sorted(features, key=lambda f: f["properties"]["name"]):
        rings = []
        for ring in rings_of(feature["geometry"]):
            projected = [
                ((lon - min_lon) * kx * scale, (max_lat - lat) * scale) for lon, lat in ring
            ]
            simple = simplify(projected, TOLERANCE)
            if len(simple) >= 4 and ring_area(simple) >= MIN_RING_AREA:
                flat = []
                for x, y in simple[:-1]:
                    flat += [round(x), round(y)]
                rings.append(flat)
        if rings:
            name = feature["properties"]["name"].title().replace("-Eastern", "-eastern")
            areas.append({"name": name, "rings": rings})

    with open(OUT, "w") as out:
        out.write("// Generated by scripts/geo/build_singapore_area_map.py. Do not edit.\n")
        out.write(
            "// URA Master Plan 2014 planning areas, data.gov.sg (Singapore Open Data Licence).\n\n"
        )
        out.write(
            "export const SINGAPORE_MAP_PROJECTION = "
            + json.dumps(
                {
                    "width": WIDTH,
                    "height": height,
                    "minLon": min_lon,
                    "maxLat": max_lat,
                    "lonScale": kx * scale,
                    "latScale": scale,
                }
            )
            + " as const;\n\n"
        )
        out.write("/** Each planning area's outline rings as flat [x0, y0, x1, y1, ...] lists. */\n")
        out.write("export const SINGAPORE_PLANNING_AREAS: readonly { name: string; rings: number[][] }[] = ")
        out.write(json.dumps(areas, separators=(",", ":")))
        out.write(";\n")


if __name__ == "__main__":
    main(sys.argv[1])
