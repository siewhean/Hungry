type Primitive = string | number | boolean | null;
type InsertOptions = {
  conflictColumns?: string[];
  doNothing?: boolean;
  updateColumns?: string[];
};

const RELATIVE_TIME_BASE_ISO = "2026-04-17T00:00:00.000Z";
const RELATIVE_TIME_BASE_MS = Date.parse(RELATIVE_TIME_BASE_ISO);

function toSqlString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function toSqlUuidFromSeed(seed: string): string {
  const digest = createHash("sha1").update(seed).digest("hex").slice(0, 32);
  const chars = digest.split("");
  chars[12] = "4";
  const variantNibble = parseInt(chars[16], 16);
  chars[16] = ((variantNibble & 0x3) | 0x8).toString(16);
  return `${chars.slice(0, 8).join("")}-${chars.slice(8, 12).join("")}-${chars.slice(12, 16).join("")}-${chars.slice(16, 20).join("")}-${chars.slice(20, 32).join("")}`;
}

function toSqlValue(value: Primitive): string {
  if (value === null) return "null";
  if (typeof value === "string") return toSqlString(value);
  if (typeof value === "boolean") return value ? "true" : "false";
  return Number.isFinite(value) ? String(value) : "null";
}

function toSqlTextArray(values: string[] | undefined): string {
  if (!values || values.length === 0) return "ARRAY[]::text[]";
  return `ARRAY[${values.map((value) => toSqlString(value)).join(", ")}]::text[]`;
}

function toSqlJson(value: unknown): string {
  return `${toSqlString(JSON.stringify(value ?? {}))}::jsonb`;
}

function toIsoMaybeRelative(raw: string | undefined): string {
  if (!raw) return new Date(RELATIVE_TIME_BASE_MS).toISOString();
  const direct = Date.parse(raw);
  if (!Number.isNaN(direct)) return new Date(direct).toISOString();

  const relative = raw.trim().toLowerCase();
  const hours = /^(\d+)\s*h\s*ago$/.exec(relative);
  if (hours) {
    const date = new Date(RELATIVE_TIME_BASE_MS - Number(hours[1]) * 60 * 60 * 1000);
    return date.toISOString();
  }

  const days = /^(\d+)\s*d\s*ago$/.exec(relative);
  if (days) {
    const date = new Date(RELATIVE_TIME_BASE_MS - Number(days[1]) * 24 * 60 * 60 * 1000);
    return date.toISOString();
  }

  return new Date(RELATIVE_TIME_BASE_MS).toISOString();
}

function insertStatement(
  table: string,
  columns: string[],
  rows: string[],
  options: InsertOptions = {},
): string {
  if (rows.length === 0) return `-- ${table}: no rows`;
  let conflictClause = "";
  if (options.conflictColumns && options.conflictColumns.length > 0) {
    if (options.doNothing) {
      conflictClause = `\non conflict (${options.conflictColumns.join(", ")}) do nothing`;
    } else {
      const updateColumns =
        options.updateColumns ??
        columns.filter((column) => !options.conflictColumns?.includes(column));
      conflictClause =
        updateColumns.length === 0
          ? `\non conflict (${options.conflictColumns.join(", ")}) do nothing`
          : `\non conflict (${options.conflictColumns.join(", ")}) do update set ${updateColumns
              .map((column) => `${column} = excluded.${column}`)
              .join(", ")}`;
    }
  }
  return `insert into ${table} (${columns.join(", ")}) values\n${rows.join(",\n")}${conflictClause};`;
}

