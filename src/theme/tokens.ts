const scaleTypography = <T extends { fontSize: number; lineHeight: number }>(variant: T) => ({
  ...variant,
  fontSize: scaleTypographyLevel(variant.fontSize),
  lineHeight: variant.lineHeight + typographyLevelUp,
});

